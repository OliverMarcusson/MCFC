use mcfc::compiler::{CompileOptions, compile_project, compile_source};

/// These tests check how the backend lowers code, so they read its output
/// before the whole-pack optimizer rewrites it.
fn lowering() -> CompileOptions {
    CompileOptions {
        optimize_pack: false,
        ..CompileOptions::default()
    }
}

#[test]
fn compiles_straight_line_program() {
    let source = r#"
void main() {
    var a = 5;
    var b = 7;
    var text = "done";
    b = a + b;
    mc("say done");
    return;
}
"#;

    let result = compile_source(source, &lowering()).expect("source should compile");
    assert!(
        result
            .artifacts
            .files
            .contains_key("data/mcfc/function/main.mcfunction")
    );
    let pack_mcmeta = result.artifacts.files.get("pack.mcmeta").unwrap();
    assert!(pack_mcmeta.contains("\"min_format\": [121, 0]"));
    assert!(pack_mcmeta.contains("\"max_format\": [121, 0]"));
    assert!(pack_mcmeta.contains("Generated by mcfc for Minecraft 26.3"));
    let load_tag = result
        .artifacts
        .files
        .get("data/load/tags/function/load.json")
        .unwrap();
    assert!(load_tag.contains("\"mcfc:generated/load_status\""));
    assert!(load_tag.contains("\"mcfc:main\""));
    let minecraft_load = result
        .artifacts
        .files
        .get("data/minecraft/tags/function/load.json")
        .unwrap();
    assert!(minecraft_load.contains("\"#load:_private/load\""));
    let main = result
        .artifacts
        .files
        .get("data/mcfc/function/generated/main__d0__entry.mcfunction")
        .unwrap();
    assert!(main.contains("scoreboard players set $d0_main_a mcfc 5"));
    assert!(main.contains("say done"));
}

